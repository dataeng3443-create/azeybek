using PbitToSsasConverter.Web.Infrastructure;
using PbitToSsasConverter.Web.Models.Pbit;
using PbitToSsasConverter.Web.Models.Conversion;

namespace PbitToSsasConverter.Web.Services.Pbit;

public interface IPbitPackageReader
{
    Task<PbitPackageContext> ReadAsync(Guid jobId, string sourcePath, string directory, CancellationToken ct);
}
public sealed class PbitPackageReader(SecureArchiveExtractor extractor, PbitPackageInspector inspector) : IPbitPackageReader
{
    public async Task<PbitPackageContext> ReadAsync(Guid jobId, string sourcePath, string directory, CancellationToken ct)
    {
        await using (var input = File.OpenRead(sourcePath))
        {
            var header = new byte[4];
            var read = await input.ReadAsync(header, ct);
            if (read != 4 || header[0] != 0x50 || header[1] != 0x4b || header[2] != 3 || header[3] != 4)
                throw new ConversionException("UNSUPPORTED_PACKAGE", "The uploaded Power BI template is not a supported ZIP package. It may be corrupted or use an unsupported Power BI Desktop format.");
        }
        try
        {
            var entries = await extractor.ExtractAsync(sourcePath, Path.Combine(directory, "extracted"), ct);
            var artifacts = new List<PbitArtifact>();
            foreach (var entry in entries) artifacts.Add(await inspector.InspectAsync(entry.Name, entry.Path, entry.Length, ct));
            return new(jobId, directory, artifacts);
        }
        catch (InvalidDataException ex) { throw new ConversionException("ARCHIVE_INVALID", "The uploaded Power BI template could not be read. The file may be corrupted or generated by an unsupported Power BI Desktop version.", ex); }
    }
}
